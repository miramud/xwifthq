"use client";

import { useId, useMemo, useState } from "react";
import { ChevronDown, KeyRound } from "lucide-react";
import { Chip, SearchField, cx } from "@/components/workspace/kit";
import type { Catalogue, PermissionModule } from "@/lib/api/platform-access-client";
import { IconTile } from "@/suite/lms/components/ui/ws";
import { moduleHue } from "../ui";

/**
 * The permission catalogue as a grid you can read and set: module, then
 * feature, then action. Every feature row can be granted whole, and every module header
 * says how much of it the role holds, so a role reads at a glance.
 *
 * The catalogue is generated by the API from the routes themselves, so what
 * is listed here is exactly what the platform enforces.
 */
export default function PermissionMatrix({
  catalogue,
  value,
  onChange,
  readOnly = false,
}: {
  catalogue: Catalogue;
  value: string[];
  onChange?: (next: string[]) => void;
  readOnly?: boolean;
}) {
  const [filter, setFilter] = useState("");
  const [collapsed, setCollapsed] = useState<Record<string, boolean>>({});
  const held = useMemo(() => new Set(value), [value]);

  const modules = useMemo(() => {
    const q = filter.trim().toLowerCase();
    if (!q) return catalogue.modules;
    return catalogue.modules
      .map((m) => ({
        ...m,
        features: m.features
          .map((f) => ({
            ...f,
            permissions: f.permissions.filter(
              (p) =>
                p.label.toLowerCase().includes(q) ||
                p.key.toLowerCase().includes(q) ||
                f.label.toLowerCase().includes(q) ||
                m.label.toLowerCase().includes(q),
            ),
          }))
          .filter((f) => f.permissions.length > 0),
      }))
      .filter((m) => m.features.length > 0);
  }, [catalogue, filter]);

  const set = (keys: string[], on: boolean) => {
    if (readOnly || !onChange) return;
    const next = new Set(held);
    for (const k of keys) {
      if (on) next.add(k);
      else next.delete(k);
    }
    onChange([...next].sort());
  };

  const total = catalogue.modules.reduce(
    (n, m) => n + m.features.reduce((x, f) => x + f.permissions.length, 0),
    0,
  );

  return (
    <div className="space-y-4">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <SearchField value={filter} onChange={setFilter} placeholder="Filter permissions…" label="Filter permissions" className="sm:w-80" />
        <p className="text-sm text-neutral-600" aria-live="polite">
          <span className="font-semibold tabular-nums text-neutral-900">{value.length}</span> of {total} permissions
        </p>
      </div>

      {modules.length === 0 && (
        <p className="rounded-2xl bg-neutral-50 px-4 py-6 text-center text-sm text-neutral-500">No permissions match that filter.</p>
      )}

      {modules.map((m) => (
        <ModuleBlock
          key={m.key}
          module={m}
          held={held}
          readOnly={readOnly}
          collapsed={Boolean(collapsed[m.key]) && !filter}
          onToggleCollapsed={() => setCollapsed((c) => ({ ...c, [m.key]: !c[m.key] }))}
          onSet={set}
        />
      ))}
    </div>
  );
}

function ModuleBlock({
  module: m,
  held,
  readOnly,
  collapsed,
  onToggleCollapsed,
  onSet,
}: {
  module: PermissionModule;
  held: Set<string>;
  readOnly: boolean;
  collapsed: boolean;
  onToggleCollapsed: () => void;
  onSet: (keys: string[], on: boolean) => void;
}) {
  const id = useId();
  const keys = m.features.flatMap((f) => f.permissions.map((p) => p.key));
  const count = keys.filter((k) => held.has(k)).length;
  const all = count === keys.length && keys.length > 0;

  return (
    <section className="overflow-hidden rounded-2xl border border-neutral-200/80 bg-white" aria-labelledby={`${id}-h`}>
      <header className="flex items-center gap-3 border-b border-neutral-100 bg-neutral-50/70 px-4 py-3">
        <button
          type="button"
          onClick={onToggleCollapsed}
          aria-expanded={!collapsed}
          aria-controls={`${id}-body`}
          className="flex min-w-0 flex-1 cursor-pointer items-center gap-3 rounded-lg text-left outline-none focus-visible:ring-2 focus-visible:ring-primary-300"
        >
          <ChevronDown size={16} className={cx("shrink-0 text-neutral-500 transition-transform", collapsed && "-rotate-90")} aria-hidden />
          <IconTile icon={KeyRound} hue={moduleHue(m.key)} size={36} />
          <h3 id={`${id}-h`} className="truncate text-[15px] font-bold tracking-tight text-neutral-900">
            {m.label}
          </h3>
          <Chip hue={count === 0 ? "slate" : moduleHue(m.key)}>
            {count}/{keys.length}
          </Chip>
        </button>
        {!readOnly && (
          <label className="flex shrink-0 cursor-pointer items-center gap-2 text-xs font-medium text-neutral-600">
            <input
              type="checkbox"
              checked={all}
              ref={(el) => {
                if (el) el.indeterminate = count > 0 && !all;
              }}
              onChange={(e) => onSet(keys, e.target.checked)}
              className="h-4 w-4 rounded border-neutral-300 text-primary-600 focus:ring-2 focus:ring-primary-500"
              aria-label={`All of ${m.label}`}
            />
            <span className="hidden sm:inline">All</span>
          </label>
        )}
      </header>

      {!collapsed && (
        <div id={`${id}-body`} className="divide-y divide-neutral-100">
          {m.features.map((f) => {
            const fKeys = f.permissions.map((p) => p.key);
            const fCount = fKeys.filter((k) => held.has(k)).length;
            const fAll = fCount === fKeys.length;
            return (
              <div key={f.key} className="flex flex-col gap-3 px-4 py-3 md:flex-row md:items-start">
                <div className="flex items-center gap-2 md:w-56 md:shrink-0 md:pt-1">
                  {!readOnly && (
                    <input
                      type="checkbox"
                      checked={fAll}
                      ref={(el) => {
                        if (el) el.indeterminate = fCount > 0 && !fAll;
                      }}
                      onChange={(e) => onSet(fKeys, e.target.checked)}
                      className="h-4 w-4 rounded border-neutral-300 text-primary-600 focus:ring-2 focus:ring-primary-500"
                      aria-label={`All of ${f.label}`}
                    />
                  )}
                  <span className="text-sm font-medium text-neutral-800">{f.label}</span>
                </div>
                <ul className="flex flex-1 flex-wrap gap-2" aria-label={`${f.label} permissions`}>
                  {f.permissions.map((p) => {
                    const on = held.has(p.key);
                    return (
                      <li key={p.key}>
                        <label
                          title={p.description ?? p.key}
                          className={cx(
                            "inline-flex min-h-11 items-center gap-2 rounded-xl border px-3 py-1.5 text-sm transition-colors",
                            readOnly ? "cursor-default" : "cursor-pointer",
                            on
                              ? "border-primary-300 bg-primary-50 text-primary-800"
                              : "border-neutral-200 bg-white text-neutral-600",
                            !readOnly && !on && "hover:border-neutral-300 hover:bg-neutral-50",
                          )}
                        >
                          <input
                            type="checkbox"
                            checked={on}
                            disabled={readOnly}
                            onChange={(e) => onSet([p.key], e.target.checked)}
                            className="h-4 w-4 rounded border-neutral-300 text-primary-600 focus:ring-2 focus:ring-primary-500 disabled:opacity-70"
                          />
                          {p.label}
                        </label>
                      </li>
                    );
                  })}
                </ul>
              </div>
            );
          })}
        </div>
      )}
    </section>
  );
}
